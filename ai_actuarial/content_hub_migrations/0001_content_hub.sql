CREATE TABLE source_snapshots (
    source_snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL UNIQUE,
    snapshot_sha256 CHAR(64) NOT NULL CHECK (snapshot_sha256 ~ '^[0-9a-f]{64}$'),
    snapshot_bytes BIGINT NOT NULL CHECK (snapshot_bytes >= 0),
    sqlite_user_version INTEGER NOT NULL CHECK (sqlite_user_version = 16),
    manifest_sha256 CHAR(64) NOT NULL CHECK (manifest_sha256 ~ '^[0-9a-f]{64}$'),
    staging_database_name TEXT,
    staging_snapshot_sha256 CHAR(64),
    imported_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        staging_snapshot_sha256 IS NULL
        OR staging_snapshot_sha256 = snapshot_sha256
    )
);

CREATE FUNCTION prevent_source_snapshot_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'content hub source snapshots are immutable';
END;
$$;

CREATE TRIGGER source_snapshots_are_immutable
BEFORE UPDATE OR DELETE ON source_snapshots
FOR EACH ROW EXECUTE FUNCTION prevent_source_snapshot_mutation();

CREATE TABLE source_table_counts (
    source_snapshot_id BIGINT NOT NULL REFERENCES source_snapshots(source_snapshot_id),
    table_name TEXT NOT NULL,
    row_count BIGINT NOT NULL CHECK (row_count >= 0),
    PRIMARY KEY (source_snapshot_id, table_name)
);

CREATE TABLE content_blobs (
    sha256 CHAR(64) PRIMARY KEY CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    byte_size BIGINT CHECK (byte_size IS NULL OR byte_size >= 0),
    cas_relpath TEXT NOT NULL,
    availability TEXT NOT NULL CHECK (availability IN ('present', 'missing')),
    verified_at TIMESTAMPTZ,
    CHECK (
        (availability = 'present' AND verified_at IS NOT NULL AND byte_size IS NOT NULL)
        OR (availability = 'missing' AND verified_at IS NULL)
    )
);

CREATE TABLE content_versions (
    content_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_value_json TEXT NOT NULL,
    url_identity_sha256 CHAR(64) CHECK (
        url_identity_sha256 IS NULL OR url_identity_sha256 ~ '^[0-9a-f]{64}$'
    ),
    raw_sha256 CHAR(64) CHECK (raw_sha256 IS NULL OR raw_sha256 ~ '^[0-9a-f]{64}$'),
    identity_key CHAR(64) NOT NULL UNIQUE CHECK (identity_key ~ '^[0-9a-f]{64}$'),
    blob_sha256 CHAR(64) REFERENCES content_blobs(sha256),
    CHECK (
        (raw_sha256 IS NULL AND blob_sha256 IS NULL)
        OR raw_sha256 = blob_sha256
    )
);

CREATE UNIQUE INDEX content_versions_url_hash
ON content_versions(url_identity_sha256, raw_sha256)
WHERE url_identity_sha256 IS NOT NULL AND raw_sha256 IS NOT NULL;

CREATE INDEX content_versions_url_lookup ON content_versions(url_identity_sha256);

CREATE TABLE source_file_observations (
    source_snapshot_id BIGINT NOT NULL REFERENCES source_snapshots(source_snapshot_id),
    legacy_file_id TEXT NOT NULL,
    content_version_id BIGINT NOT NULL REFERENCES content_versions(content_version_id),
    file_url_json TEXT NOT NULL,
    raw_sha256 CHAR(64) CHECK (raw_sha256 IS NULL OR raw_sha256 ~ '^[0-9a-f]{64}$'),
    source_byte_size BIGINT CHECK (source_byte_size IS NULL OR source_byte_size >= 0),
    artifact_byte_size BIGINT CHECK (artifact_byte_size IS NULL OR artifact_byte_size >= 0),
    deleted_at_json TEXT NOT NULL,
    availability TEXT NOT NULL CHECK (availability IN ('present', 'missing')),
    cas_relpath TEXT,
    verified_sha256 CHAR(64),
    legacy_metadata_json TEXT NOT NULL,
    PRIMARY KEY (source_snapshot_id, legacy_file_id),
    CHECK (
        (availability = 'present' AND cas_relpath IS NOT NULL
         AND verified_sha256 = raw_sha256)
        OR (availability = 'missing' AND cas_relpath IS NULL
            AND verified_sha256 IS NULL)
    )
);

CREATE INDEX source_file_observations_url
ON source_file_observations(source_snapshot_id, legacy_file_id);

CREATE TABLE source_record_map (
    source_snapshot_id BIGINT NOT NULL REFERENCES source_snapshots(source_snapshot_id),
    source_table TEXT NOT NULL CHECK (source_table IN ('files', 'catalog_items')),
    legacy_pk_json TEXT NOT NULL,
    content_version_id BIGINT NOT NULL REFERENCES content_versions(content_version_id),
    source_metadata_json TEXT NOT NULL DEFAULT '{}',
    PRIMARY KEY (source_snapshot_id, source_table, legacy_pk_json)
);

CREATE INDEX source_record_map_version
ON source_record_map(content_version_id);

CREATE TABLE text_variants (
    text_variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_snapshot_id BIGINT NOT NULL REFERENCES source_snapshots(source_snapshot_id),
    content_version_id BIGINT NOT NULL REFERENCES content_versions(content_version_id),
    source_table TEXT NOT NULL CHECK (source_table IN ('files', 'catalog_items')),
    source_pk_json TEXT NOT NULL,
    field_name TEXT NOT NULL CHECK (
        field_name IN ('title', 'keywords', 'keywords_json', 'category', 'summary', 'markdown_content')
    ),
    payload_value_json TEXT NOT NULL,
    payload_is_null BOOLEAN NOT NULL,
    payload_sha256 CHAR(64) NOT NULL CHECK (payload_sha256 ~ '^[0-9a-f]{64}$'),
    language_code TEXT NOT NULL DEFAULT 'und',
    language_candidates_json TEXT NOT NULL DEFAULT '[]',
    language_detection_json TEXT NOT NULL DEFAULT '{}',
    model_identity_json TEXT NOT NULL DEFAULT '"unknown"',
    recipe_identity_json TEXT NOT NULL DEFAULT '"unknown"',
    provenance_json TEXT NOT NULL DEFAULT '{}',
    UNIQUE (source_snapshot_id, source_table, source_pk_json, field_name, payload_sha256)
);

CREATE INDEX text_variants_version_field
ON text_variants(content_version_id, field_name, source_snapshot_id);

CREATE TABLE legacy_index_artifacts (
    legacy_index_artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_snapshot_id BIGINT NOT NULL REFERENCES source_snapshots(source_snapshot_id),
    legacy_kb_id_json TEXT NOT NULL,
    artifact_kind TEXT NOT NULL,
    source_path_json TEXT,
    artifact_relpath TEXT,
    sha256 CHAR(64) CHECK (sha256 IS NULL OR sha256 ~ '^[0-9a-f]{64}$'),
    byte_size BIGINT CHECK (byte_size IS NULL OR byte_size >= 0),
    availability TEXT NOT NULL CHECK (availability IN ('present', 'missing')),
    embedding_provider_json TEXT NOT NULL DEFAULT '"unknown"',
    embedding_model_json TEXT NOT NULL DEFAULT '"unknown"',
    embedding_dimension INTEGER CHECK (embedding_dimension IS NULL OR embedding_dimension > 0),
    profile_id_json TEXT NOT NULL DEFAULT '"unknown"',
    source_metadata_json TEXT NOT NULL DEFAULT '{}',
    CHECK (
        (availability = 'present' AND artifact_relpath IS NOT NULL AND sha256 IS NOT NULL)
        OR (availability = 'missing')
    ),
    UNIQUE (source_snapshot_id, legacy_kb_id_json, artifact_kind, artifact_relpath)
);

CREATE INDEX legacy_index_artifacts_source
ON legacy_index_artifacts(source_snapshot_id, legacy_kb_id_json);
