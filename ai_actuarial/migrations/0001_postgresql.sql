CREATE OR REPLACE FUNCTION ai_julianday(value TEXT) RETURNS DOUBLE PRECISION
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
    RETURN EXTRACT(EPOCH FROM value::timestamptz) / 86400.0 + 2440587.5;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$;
CREATE OR REPLACE FUNCTION ai_json_valid(value TEXT) RETURNS BOOLEAN
LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN
    PERFORM value::jsonb;
    RETURN TRUE;
EXCEPTION WHEN OTHERS THEN
    RETURN FALSE;
END;
$$;
CREATE OR REPLACE FUNCTION ai_json_extract(value TEXT, path TEXT) RETURNS TEXT
LANGUAGE plpgsql IMMUTABLE AS $$
DECLARE result JSONB;
BEGIN
    result := value::jsonb #> string_to_array(regexp_replace(path, '^\$\.?', ''), '.');
    IF result IS NULL OR jsonb_typeof(result) = 'null' THEN RETURN NULL; END IF;
    IF jsonb_typeof(result) = 'string' THEN RETURN result #>> '{}'; END IF;
    RETURN result::text;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$;
